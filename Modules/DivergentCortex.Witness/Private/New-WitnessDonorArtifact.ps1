function New-WitnessDonorArtifact {
    <#
    .SYNOPSIS
        Builds the standalone logger from the runtime loader's source order.
    .PARAMETER ModuleRoot
        Module base supplied by the build entry point.
    .PARAMETER OutputPath
        Destination for the generated standalone script.
    .OUTPUTS
        PSCustomObject with Ok, Written, OutputPath, SourceCount and Reason.
    #>
    [CmdletBinding(SupportsShouldProcess)]
    [OutputType([pscustomobject])]
    param (
        [Parameter(Mandatory)]
        [ValidateNotNullOrEmpty()]
        [string]$ModuleRoot,
        [Parameter(Mandatory)]
        [ValidateNotNullOrEmpty()]
        [string]$OutputPath
    )

    Write-Log -Message "Building standalone Witness artifact at '$OutputPath'" -Severity Info
    $result = [pscustomobject]@{
        Ok = $false; Written = $false; OutputPath = $OutputPath
        SourceCount = 0; Reason = $null
    }
    $loaderPath = Join-Path $ModuleRoot 'DivergentCortex.Witness.psm1'
    $tokens = $null
    $parseErrors = $null
    try {
        Write-Log -Message "Parsing Witness loader '$loaderPath'" -Severity Verbose
        $loader = [System.Management.Automation.Language.Parser]::ParseFile($loaderPath, [ref]$tokens, [ref]$parseErrors)
        if ($parseErrors.Count -gt 0) {
            Write-Log -Message "Witness loader '$loaderPath' has parse errors: $parseErrors" -Severity Error
            $result.Reason = 'LoaderParseFailed'
            return $result
        }
        Write-Log -Message "Parsed Witness loader '$loaderPath'" -Severity Verbose
    }
    catch {
        Write-Log -Message "Parsing '$loaderPath' failed: $($_.Exception.GetType().Name) at line $($_.InvocationInfo.ScriptLineNumber): $($_.Exception.Message)" -Severity Error
        $result.Reason = 'LoaderReadFailed'
        return $result
    }

    $parts = [System.Collections.Generic.List[string]]::new()
    $parts.Add('# generated by Build-WitnessDonor.ps1 from canonical source; do not edit')
    $parts.Add('# strict mode stays in module scope and must not leak into dot-source callers')
    foreach ($statement in $loader.EndBlock.Statements) {
        if ($statement -is [System.Management.Automation.Language.AssignmentStatementAst] -and
            $statement.Left -is [System.Management.Automation.Language.VariableExpressionAst] -and
            $statement.Left.VariablePath.UserPath -like 'script:Witness*') {
            $parts.Add($statement.Extent.Text)
        }
    }

    $sourceCommands = $loader.FindAll({
        param($node)
        $node -is [System.Management.Automation.Language.CommandAst] -and
        $node.InvocationOperator -eq [System.Management.Automation.Language.TokenKind]::Dot
    }, $false)

    foreach ($sourceCommand in $sourceCommands) {
        $expression = $sourceCommand.CommandElements[0]
        if ($expression -isnot [System.Management.Automation.Language.ParenExpressionAst]) {
            Write-Log -Message "Unsupported dot-source expression in '$loaderPath': $($sourceCommand.Extent.Text)" -Severity Error
            $result.Reason = 'UnsupportedLoader'
            return $result
        }
        $elements = $expression.Pipeline.PipelineElements[0].CommandElements
        if ($elements.Count -ne 3 -or $elements[0].Value -ne 'Join-Path' -or
            $elements[1] -isnot [System.Management.Automation.Language.VariableExpressionAst] -or
            $elements[2] -isnot [System.Management.Automation.Language.StringConstantExpressionAst]) {
            Write-Log -Message "Unsupported source path in '$loaderPath': $($sourceCommand.Extent.Text)" -Severity Error
            $result.Reason = 'UnsupportedLoader'
            return $result
        }
        $tier = switch ($elements[1].VariablePath.UserPath) {
            'privatePath' { 'Private' }
            'publicPath' { 'Public' }
        }
        if (-not $tier -or $elements[2].Value -ne [System.IO.Path]::GetFileName($elements[2].Value)) {
            Write-Log -Message "Witness source must be a direct Public or Private file: $($sourceCommand.Extent.Text)" -Severity Error
            $result.Reason = 'UnsupportedLoader'
            return $result
        }
        $sourcePath = Join-Path (Join-Path $ModuleRoot $tier) $elements[2].Value
        try {
            Write-Log -Message "Reading Witness artifact source '$sourcePath'" -Severity Verbose
            $source = Get-Content -LiteralPath $sourcePath -Raw -Encoding UTF8 -ErrorAction Stop
            Write-Log -Message "Read Witness artifact source '$sourcePath'" -Severity Verbose
        }
        catch {
            Write-Log -Message "Reading '$sourcePath' failed: $($_.Exception.GetType().Name) at line $($_.InvocationInfo.ScriptLineNumber): $($_.Exception.Message)" -Severity Error
            $result.Reason = 'SourceReadFailed'
            return $result
        }
        $sourceTokens = $null
        $sourceErrors = $null
        $null = [System.Management.Automation.Language.Parser]::ParseInput($source, [ref]$sourceTokens, [ref]$sourceErrors)
        if ($sourceErrors.Count -gt 0) {
            Write-Log -Message "Witness source '$sourcePath' has parse errors: $sourceErrors" -Severity Error
            $result.Reason = 'SourceParseFailed'
            return $result
        }
        $parts.Add($source.TrimEnd())
        $result.SourceCount++
    }

    if ($result.SourceCount -eq 0) {
        Write-Log -Message "Witness loader '$loaderPath' contains no sources" -Severity Error
        $result.Reason = 'NoSources'
        return $result
    }
    $content = [string]::Join("`n`n", $parts) + "`n"
    $artifactTokens = $null
    $artifactErrors = $null
    $null = [System.Management.Automation.Language.Parser]::ParseInput($content, [ref]$artifactTokens, [ref]$artifactErrors)
    if ($artifactErrors.Count -gt 0) {
        Write-Log -Message "Generated Witness artifact has parse errors: $artifactErrors" -Severity Error
        $result.Reason = 'ArtifactParseFailed'
        return $result
    }
    if (-not $PSCmdlet.ShouldProcess($OutputPath, 'Write generated Witness script')) {
        $result.Ok = $true
        $result.Reason = 'NotRequested'
        return $result
    }
    $parent = Split-Path -Parent $OutputPath
    try {
        Write-Log -Message "Creating Witness artifact directory '$parent'" -Severity Info
        $null = New-Item -Path $parent -ItemType Directory -Force -ErrorAction Stop
        if (-not (Test-Path -LiteralPath $parent -PathType Container)) {
            Write-Log -Message "Witness artifact directory '$parent' was not created" -Severity Error
            $result.Reason = 'DirectoryMissing'
            return $result
        }
        Write-Log -Message "Witness artifact directory '$parent' is available" -Severity Success
    }
    catch {
        Write-Log -Message "Creating '$parent' failed: $($_.Exception.GetType().Name) at line $($_.InvocationInfo.ScriptLineNumber): $($_.Exception.Message)" -Severity Error
        $result.Reason = 'DirectoryCreateFailed'
        return $result
    }
    try {
        Write-Log -Message "Writing generated Witness artifact '$OutputPath'" -Severity Info
        [System.IO.File]::WriteAllText($OutputPath, $content, [System.Text.UTF8Encoding]::new($false))
        Write-Log -Message "Wrote generated Witness artifact '$OutputPath'" -Severity Success
    }
    catch {
        Write-Log -Message "Writing '$OutputPath' failed: $($_.Exception.GetType().Name) at line $($_.InvocationInfo.ScriptLineNumber): $($_.Exception.Message)" -Severity Error
        $result.Reason = 'ArtifactWriteFailed'
        return $result
    }
    try {
        Write-Log -Message "Verifying generated Witness artifact '$OutputPath'" -Severity Verbose
        $readBack = [System.IO.File]::ReadAllText($OutputPath)
        if ($readBack -cne $content) {
            Write-Log -Message "Witness artifact '$OutputPath' differs from generated content" -Severity Error
            $result.Reason = 'ArtifactMismatch'
            return $result
        }
        Write-Log -Message "Verified Witness artifact '$OutputPath'" -Severity Verbose
    }
    catch {
        Write-Log -Message "Reading back '$OutputPath' failed: $($_.Exception.GetType().Name) at line $($_.InvocationInfo.ScriptLineNumber): $($_.Exception.Message)" -Severity Error
        $result.Reason = 'ArtifactReadbackFailed'
        return $result
    }
    $result.Ok = $true
    $result.Written = $true
    Write-Log -Message "Witness artifact verified at '$OutputPath', sources=$($result.SourceCount)" -Severity Success
    return $result
}
